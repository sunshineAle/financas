# Tours 96/97: exemplos em memória, sem alterar tabelas ou fazer chamadas mutantes à API.
from playwright.sync_api import sync_playwright, expect
import os, json
URL=os.environ.get('DAGDA_TEST_URL','http://127.0.0.1:8001/').split('?')[0]+'?modo=demo'
def tabelas(page):
    return page.evaluate("async()=>JSON.stringify((await(await fetch('/api/backup/exportar')).json()).tabelas)")
with sync_playwright() as pw:
    browser=pw.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    for width in [390,1366]:
        ctx=browser.new_context(viewport={'width':width,'height':900})
        ctx.add_init_script("localStorage.setItem('dagda-previa-demo-79-81:sf:tours',JSON.stringify({ligado:false,vistos:[]}))")
        page=ctx.new_page();erros=[]
        page.on('pageerror',lambda e:erros.append(str(e)))
        page.goto(URL,wait_until='networkidle');expect(page.locator('main')).to_be_visible(timeout=25000)
        page.evaluate("location.hash='#/manual'")
        expect(page.locator('.chip-tour').get_by_text('Regras',exact=True)).to_be_visible()
        antes=tabelas(page)
        page.evaluate("""()=>{window.__chamadasMutantesTour=[];const original=window.fetch;window.fetch=function(url,op={}){if(String(url).startsWith('/api/')&&!['GET','HEAD'].includes((op.method||'GET').toUpperCase()))window.__chamadasMutantesTour.push(String(url));return original.apply(this,arguments)}}""")
        page.get_by_role('button',name='Regras',exact=True).click()
        tour=page.locator('[data-tour]');ex=page.locator('[data-tour-exemplos]')
        expect(ex).to_have_attribute('data-tour-chave','regras')
        expect(tour.locator('img')).to_have_count(0)
        expect(ex.locator('[data-exemplo-regras-blocos] .mini-card')).to_have_count(4)
        assert 'Mercado do Bairro' in ex.inner_text()
        ex.get_by_role('button',name='Exemplo: adicionar em Regras de despesa',exact=True).click()
        expect(ex).to_have_attribute('data-tour-passo','1')
        expect(tour.get_by_role('button',name='Passo 2: Adicionar no +',exact=True)).to_have_attribute('aria-current','step')
        ex.get_by_role('button',name='Criar regra',exact=True).click()
        expect(ex.locator('[data-tour-resultado]')).to_contain_text('Nenhuma regra sua foi criada')
        page.locator('[data-tour-seguir]').click()
        expect(ex).to_have_attribute('data-tour-passo','2')
        ex.get_by_role('button',name='Ver todas as regras',exact=True).click()
        expect(ex.locator('[data-exemplo-popup-regras] li')).to_have_count(5)
        page.screenshot(path=f'/tmp/tour-regras-96-{width}.png',full_page=True)
        tour.get_by_role('button',name='Passo 4: Editar, pausar ou excluir',exact=True).click()
        ex.get_by_role('button',name='Pausar',exact=True).click()
        expect(ex.locator('[data-tour-resultado]')).to_contain_text('pausada')
        ex.get_by_role('button',name='Excluir',exact=True).click()
        expect(ex.locator('[data-tour-resultado]')).to_contain_text('lançamentos já existentes não são apagados')
        page.locator('[data-tour-seguir]').click();expect(tour).not_to_be_visible()
        assert tabelas(page)==antes
        page.get_by_role('button',name='A revisar',exact=True).click()
        expect(ex).to_have_attribute('data-tour-chave','revisar')
        expect(tour.locator('img')).to_have_count(0)
        expect(ex.locator('[data-exemplo-transferencia]')).to_be_visible()
        ex.get_by_role('button',name='Vincular',exact=True).click()
        expect(ex.locator('[data-tour-resultado]')).to_contain_text('sem virar entrada nem despesa')
        page.locator('[data-tour-seguir]').click()
        expect(ex).to_have_attribute('data-tour-passo','1')
        ex.get_by_role('combobox').select_option('Transporte')
        ex.get_by_role('button',name='Salvar',exact=True).click()
        expect(ex.locator('[data-tour-resultado]')).to_contain_text('Transporte')
        ex.get_by_role('button',name='Ignorar',exact=True).click()
        expect(ex.locator('[data-tour-resultado]')).to_contain_text('sai dos totais e do saldo')
        page.locator('[data-tour-seguir]').click()
        expect(ex.locator('[data-exemplo-divida]')).to_be_visible()
        expect(ex.get_by_role('button',name='Vincular',exact=True)).to_have_count(0)
        assert 'não quita nem vincula' in ex.inner_text()
        ex.get_by_role('button',name='Salvar',exact=True).click()
        expect(ex.locator('[data-tour-resultado]')).to_contain_text('dívida não foi vinculada, reduzida nem quitada')
        page.screenshot(path=f'/tmp/tour-revisar-97-{width}.png',full_page=True)
        page.locator('[data-tour-seguir]').click()
        expect(ex.locator('[data-exemplo-reserva] .mini-card')).to_have_count(2)
        assert 'R$ 100,00 de principal' not in ex.inner_text()
        ex.locator('[data-exemplo-reserva] .mini-card').last.get_by_role('button',name='Vincular',exact=True).click()
        expect(ex.locator('[data-tour-resultado]')).to_contain_text('R$ 100,00 de principal e R$ 10,00 de rendimento')
        page.locator('[data-tour-seguir]').click();expect(tour).not_to_be_visible()
        assert tabelas(page)==antes
        assert page.evaluate('window.__chamadasMutantesTour')==[]
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        assert not erros,erros
        print(f'PASS tours em{width}px: exemplos preenchidos/ações sincronizadas, sem WebP antigo, dívida sem vínculo fictício, banco e API sem escrita')
        ctx.close()
    browser.close()
